import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sha256 = (bytes) => crypto.createHash('sha256').update(bytes).digest('hex');

function repoFile(file) {
  assert.equal(typeof file, 'string');
  assert.ok(file && !file.includes('\0') && !file.includes('\\') && !path.isAbsolute(file));
  assert.ok(file.split('/').every((part) => part && part !== '.' && part !== '..'));
  const resolved = path.resolve(root, file);
  assert.ok(resolved.startsWith(`${root}${path.sep}`));
  return resolved;
}

const byteArray = (bytes) => [...bytes].map((byte) => `0x${byte.toString(16).padStart(2, '0')}`).join(',');

export function generateNativeAssets(manifest = JSON.parse(fs.readFileSync(repoFile('native/lua-source-manifest.json'), 'utf8')), readBytes = (file) => fs.readFileSync(repoFile(file))) {
  const entries = manifest.resources.map((resource, index) => {
    const bytes = readBytes(resource.path);
    assert.equal(sha256(bytes), resource.sha256, `resource hash drift: ${resource.path}`);
    return { ...resource, bytes, name: `resource_${index}` };
  });
  const hostile = manifest.testOnlyHashMismatch;
  const hostileBytes = readBytes(hostile.path);
  assert.equal(sha256(hostileBytes), hostile.actualSha256, `hostile resource hash drift: ${hostile.path}`);

  const arrays = [...entries, { ...hostile, bytes: hostileBytes, name: 'resource_hostile' }]
    .map(({ name, bytes }) => `static const unsigned char ${name}[] = {${byteArray(bytes)}};`)
    .join('\n');
  const records = entries.map(({ logicalPath, sha256: hash, name }) =>
    `  {${JSON.stringify(logicalPath)}, ${name}, sizeof(${name}), {${byteArray(Buffer.from(hash, 'hex'))}}}`
  ).join(',\n');
  const hostileRecord = `  {${JSON.stringify(hostile.logicalPath)}, resource_hostile, sizeof(resource_hostile), {${byteArray(Buffer.from(hostile.compiledExpectedSha256, 'hex'))}}}`;
  const cSource = `/* Generated by scripts/generate-native-assets.mjs; do not edit. */
#include "resource_bundle.h"

#include <string.h>

${arrays}

static const AllNewMTSResource resources[] = {
${records},
#ifdef ALLNEWMTS_LUA_TESTING
${hostileRecord},
#endif
};

const AllNewMTSResource *allnewmts_resource(const char *path, size_t size) {
  size_t i;
  for (i = 0; i < sizeof(resources) / sizeof(resources[0]); i++) {
    if (strlen(resources[i].path) == size && memcmp(resources[i].path, path, size) == 0) return &resources[i];
  }
  return NULL;
}
`;

  const fixture = readBytes(manifest.adapterFixture.source).toString('utf8');
  const golden = readBytes(manifest.adapterFixture.golden).toString('utf8').replace(/\r?\n$/, '');
  const typescript = `/* Generated by scripts/generate-native-assets.mjs; do not edit. */
export const verificationFixture = ${JSON.stringify(fixture)};
export const verificationGolden = ${JSON.stringify(golden)};
`;
  return new Map([
    ['modules/allnewmts-lua/shared/resource_bundle.c', cSource],
    ['modules/allnewmts-lua/src/verification-fixture.generated.ts', typescript]
  ]);
}

function main(argument) {
  const generated = generateNativeAssets();
  for (const [file, text] of generated) {
    if (argument === '--write') fs.writeFileSync(repoFile(file), text);
    else assert.equal(fs.readFileSync(repoFile(file), 'utf8'), text, `generated native asset drift: ${file}; rerun node scripts/generate-native-assets.mjs --write`);
  }
  console.log(`${argument === '--write' ? 'WROTE' : 'PASS'} native generated assets: ${generated.size} files`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv[2]);
