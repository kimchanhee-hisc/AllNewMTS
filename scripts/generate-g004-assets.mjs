import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = 'test/oracles/sources/mts_screen/HS1200P08.xmf_';
const outputPath = 'src/generated/g004-original-xmf.ts';
const expectedBytes = 10179;
const expectedSha256 = '4d63ba22ac5339cfd3068cffa91710e0099481da81d974e2aff0ce7ae39ed53e';

assert.deepEqual(process.argv.slice(2), process.argv[2] === '--check' ? ['--check'] : [], 'usage: node scripts/generate-g004-assets.mjs [--check]');

const manifest = JSON.parse(fs.readFileSync(path.join(root, 'test/oracles/manifest.json'), 'utf8'));
const entries = manifest.sources.filter(({ path: entryPath }) => entryPath === sourcePath);
assert.equal(entries.length, 1, `expected one oracle entry for ${sourcePath}`);
assert.equal(entries[0].bytes, expectedBytes, 'oracle byte count drift');
assert.equal(entries[0].sha256, expectedSha256, 'oracle hash drift');

const bytes = fs.readFileSync(path.join(root, sourcePath));
assert.equal(bytes.length, expectedBytes, 'source byte count drift');
assert.equal(createHash('sha256').update(bytes).digest('hex'), expectedSha256, 'source hash drift');

const rows = [];
for (let offset = 0; offset < bytes.length; offset += 24) rows.push(`  ${[...bytes.subarray(offset, offset + 24)].join(', ')},`);
const output = `// Generated by scripts/generate-g004-assets.mjs. Do not edit.\nexport const g004OriginalXmfBytes = new Uint8Array([\n${rows.join('\n')}\n]);\nexport const g004OriginalXmfBytesCount = ${expectedBytes};\nexport const g004OriginalXmfSha256 = '${expectedSha256}';\n`;
const outputFile = path.join(root, outputPath);

if (process.argv[2] === '--check') {
  assert.equal(fs.readFileSync(outputFile, 'utf8'), output, `${outputPath} is stale`);
} else {
  fs.mkdirSync(path.dirname(outputFile), { recursive: true });
  fs.writeFileSync(outputFile, output);
}

console.log(`PASS G004 asset ${process.argv[2] === '--check' ? 'check' : 'generate'} ${expectedBytes} ${expectedSha256}`);
